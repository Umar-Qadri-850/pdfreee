import { PDFDocument, degrees } from 'pdf-lib'
import { PdfError, friendlyMessage } from './errors'

export type ProgressFn = (fraction: number, message?: string) => void

export async function readFileBytes(file: File): Promise<Uint8Array> {
  return new Uint8Array(await file.arrayBuffer())
}

export async function loadPdf(bytes: Uint8Array): Promise<PDFDocument> {
  try {
    return await PDFDocument.load(bytes, { updateMetadata: false })
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error)
    if (/encrypt/i.test(message)) {
      throw new PdfError('encrypted', 'This PDF is encrypted. Remove its password and try again.')
    }
    throw new PdfError('corrupt', friendlyMessage(error))
  }
}

/** Reload generated bytes and confirm the page count to avoid shipping silent corruption. */
export async function verifyPdf(bytes: Uint8Array, expectedPages?: number): Promise<void> {
  const doc = await loadPdf(bytes)
  const count = doc.getPageCount()
  if (count < 1) throw new PdfError('no-pages', 'The generated PDF contains no pages.')
  if (expectedPages !== undefined && count !== expectedPages) {
    throw new PdfError('unknown', 'The generated PDF did not match the expected page count.')
  }
}

export async function mergePdfs(files: File[], onProgress?: ProgressFn): Promise<Uint8Array> {
  const out = await PDFDocument.create()
  out.setProducer('Pdfreee')
  out.setCreator('Pdfreee (browser PDF toolkit)')

  let total = 0
  for (let i = 0; i < files.length; i++) {
    const src = await loadPdf(await readFileBytes(files[i]))
    const indices = src.getPageIndices()
    const copied = await out.copyPages(src, indices)
    copied.forEach((page) => out.addPage(page))
    total += copied.length
    onProgress?.((i + 1) / files.length, `Merged ${i + 1} of ${files.length}`)
  }
  if (total === 0) throw new PdfError('no-pages', 'None of the selected files contained pages.')

  const bytes = await out.save()
  await verifyPdf(bytes, total)
  return bytes
}

export interface SplitPart {
  name: string
  bytes: Uint8Array
}

/** Split into one document per provided page list (each list is 1-based). */
export async function splitPdf(
  bytes: Uint8Array,
  selections: number[][],
  baseName: string,
  onProgress?: ProgressFn,
): Promise<SplitPart[]> {
  const src = await loadPdf(bytes)
  const parts: SplitPart[] = []

  for (let i = 0; i < selections.length; i++) {
    const pages = selections[i]
    if (pages.length === 0) continue
    const out = await PDFDocument.create()
    const copied = await out.copyPages(src, pages.map((p) => p - 1))
    copied.forEach((page) => out.addPage(page))
    const outBytes = await out.save()
    await verifyPdf(outBytes, pages.length)
    const label = pages.length === 1 ? `${pages[0]}` : `${pages[0]}-${pages[pages.length - 1]}`
    parts.push({ name: `${baseName}-pages-${label}.pdf`, bytes: outBytes })
    onProgress?.((i + 1) / selections.length, `Created ${i + 1} of ${selections.length}`)
  }

  if (parts.length === 0) throw new PdfError('no-pages', 'No pages were selected to split.')
  return parts
}

/** Build a new PDF containing only the given 1-based pages, in the given order. */
export async function extractPages(bytes: Uint8Array, pages: number[]): Promise<Uint8Array> {
  const src = await loadPdf(bytes)
  const out = await PDFDocument.create()
  const copied = await out.copyPages(src, pages.map((p) => p - 1))
  copied.forEach((page) => out.addPage(page))
  const result = await out.save()
  await verifyPdf(result, pages.length)
  return result
}

/** Remove the given 1-based pages, keeping the rest in original order. */
export async function deletePages(bytes: Uint8Array, pagesToDelete: number[], onProgress?: ProgressFn): Promise<Uint8Array> {
  const src = await loadPdf(bytes)
  const total = src.getPageCount()
  const remove = new Set(pagesToDelete)
  const keep = Array.from({ length: total }, (_, i) => i + 1).filter((p) => !remove.has(p))
  if (keep.length === 0) throw new PdfError('no-pages', 'You cannot delete every page — keep at least one.')

  onProgress?.(0.4, 'Removing pages')
  const out = await PDFDocument.create()
  const copied = await out.copyPages(src, keep.map((p) => p - 1))
  copied.forEach((page) => out.addPage(page))
  const result = await out.save()
  await verifyPdf(result, keep.length)
  onProgress?.(1, 'Done')
  return result
}

/** Rebuild the PDF with pages in the supplied 1-based order (length must equal page count). */
export async function reorderPages(bytes: Uint8Array, order: number[]): Promise<Uint8Array> {
  const src = await loadPdf(bytes)
  const total = src.getPageCount()
  if (order.length !== total) {
    throw new PdfError('unknown', 'The new page order must include every page exactly once.')
  }
  const seen = new Set(order)
  if (seen.size !== total) {
    throw new PdfError('unknown', 'The new page order must include every page exactly once.')
  }
  const out = await PDFDocument.create()
  const copied = await out.copyPages(src, order.map((p) => p - 1))
  copied.forEach((page) => out.addPage(page))
  const result = await out.save()
  await verifyPdf(result, total)
  return result
}

export interface RotateOptions {
  angle: 90 | 180 | 270
  /** 1-based pages to rotate; omit or pass all pages to rotate everything. */
  pages?: number[]
}

export async function rotatePages(bytes: Uint8Array, options: RotateOptions, onProgress?: ProgressFn): Promise<Uint8Array> {
  const src = await loadPdf(bytes)
  const total = src.getPageCount()
  const targets = options.pages && options.pages.length > 0 ? new Set(options.pages) : null

  for (let i = 1; i <= total; i++) {
    if (targets && !targets.has(i)) continue
    const page = src.getPage(i - 1)
    const current = page.getRotation().angle
    page.setRotation(degrees(((current + options.angle) % 360 + 360) % 360))
    if (i % 25 === 0) onProgress?.(i / total, `Rotated ${i} of ${total} pages`)
  }
  onProgress?.(0.9, 'Saving')
  const result = await src.save()
  await verifyPdf(result, total)
  onProgress?.(1, 'Done')
  return result
}

export interface CropMargins {
  /** Fraction of the page width/height to trim from each edge (0–0.9). */
  top: number
  right: number
  bottom: number
  left: number
}

/**
 * Crop pages by trimming margins from each edge. The crop is applied to both the
 * media box and the crop box, so compliant viewers and printers show only the
 * kept region. Margins are fractions of each page's own (unrotated) dimensions.
 */
export async function cropPages(
  bytes: Uint8Array,
  margins: CropMargins,
  pages?: number[],
  onProgress?: ProgressFn,
): Promise<Uint8Array> {
  const src = await loadPdf(bytes)
  const total = src.getPageCount()
  const targets = pages && pages.length > 0 ? new Set(pages) : null

  const horizontal = margins.left + margins.right
  const vertical = margins.top + margins.bottom
  if (horizontal >= 0.95 || vertical >= 0.95) {
    throw new PdfError('unknown', 'Those margins are too large. Reduce them so some page remains.')
  }

  for (let i = 1; i <= total; i++) {
    if (targets && !targets.has(i)) continue
    const page = src.getPage(i - 1)
    const { width, height } = page.getSize()
    const x = margins.left * width
    const y = margins.bottom * height
    const w = width * (1 - horizontal)
    const h = height * (1 - vertical)
    if (w < 1 || h < 1) {
      throw new PdfError('unknown', 'Those margins would remove the whole page. Reduce them and try again.')
    }
    page.setCropBox(x, y, w, h)
    page.setMediaBox(x, y, w, h)
    if (i % 25 === 0) onProgress?.(i / total, `Cropped ${i} of ${total} pages`)
  }
  onProgress?.(0.9, 'Saving')
  const result = await src.save()
  await verifyPdf(result, total)
  onProgress?.(1, 'Done')
  return result
}

export async function getPageCount(bytes: Uint8Array): Promise<number> {
  return (await loadPdf(bytes)).getPageCount()
}

export function getPageSizes(bytes: Uint8Array): Promise<{ width: number; height: number }[]> {
  return loadPdf(bytes).then((doc) =>
    doc.getPages().map((page) => {
      const { width, height } = page.getSize()
      const rotation = page.getRotation().angle
      const swapped = rotation === 90 || rotation === 270
      return { width: swapped ? height : width, height: swapped ? width : height }
    }),
  )
}
