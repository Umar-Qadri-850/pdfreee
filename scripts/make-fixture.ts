/**
 * Generates a small, deterministic 4-page PDF with SELECTABLE text for manual
 * and automated testing. Run with: npm run fixture
 *
 * Each page has a unique marker (PDFREE_FIXTURE_PAGE_N) so tools that move or
 * drop pages can be verified by eye, and the text is real (drawn with an
 * embedded Helvetica font) so "PDF to text" has something to extract.
 */
import { mkdir, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { dirname, resolve } from 'node:path'
import { PDFDocument, StandardFonts, rgb } from 'pdf-lib'

const OUT = resolve(dirname(fileURLToPath(import.meta.url)), '../test/fixtures/sample-4page.pdf')

const PAGE_WIDTH = 595.28
const PAGE_HEIGHT = 841.89

async function main() {
  const doc = await PDFDocument.create()
  doc.setTitle('Pdfreee test fixture')
  doc.setAuthor('Pdfreee')
  const font = await doc.embedFont(StandardFonts.Helvetica)
  const bold = await doc.embedFont(StandardFonts.HelveticaBold)

  const sizes: [number, number][] = [
    [PAGE_WIDTH, PAGE_HEIGHT],
    [PAGE_WIDTH, PAGE_HEIGHT],
    [PAGE_HEIGHT, PAGE_WIDTH],
    [PAGE_WIDTH, PAGE_HEIGHT],
  ]

  sizes.forEach(([width, height], index) => {
    const page = doc.addPage([width, height])
    const n = index + 1
    page.drawText(`Pdfreee fixture — page ${n}`, {
      x: 64,
      y: height - 96,
      size: 24,
      font: bold,
      color: rgb(0.11, 0.09, 0.08),
    })
    page.drawText(`PDFREE_FIXTURE_PAGE_${n}`, {
      x: 64,
      y: height - 132,
      size: 14,
      font,
      color: rgb(0.9, 0.28, 0.3),
    })
    const body = [
      `This is page ${n} of a ${sizes.length}-page sample generated by Pdfreee.`,
      'The text on this page is real, selectable text — not an image.',
      `Page size: ${Math.round(width)} x ${Math.round(height)} pt.`,
      'Use this file to try every tool: merge, split, reorder, rotate,',
      'extract, delete, add page numbers, watermark, compress and PDF to text.',
    ]
    body.forEach((line, i) => {
      page.drawText(line, {
        x: 64,
        y: height - 180 - i * 22,
        size: 12,
        font,
        color: rgb(0.2, 0.2, 0.22),
      })
    })
  })

  const bytes = await doc.save()
  await mkdir(dirname(OUT), { recursive: true })
  await writeFile(OUT, bytes)
  console.log(`[fixture] Wrote ${OUT} (${bytes.length} bytes, ${sizes.length} pages)`)
}

main().catch((error) => {
  console.error(error)
  process.exit(1)
})
